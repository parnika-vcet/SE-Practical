# 1. Waterfall Model

# This is the oldest model. Work flows step by step, like a waterfall. 
# You finish one phase fully before starting the next, and you don’t go back.

# Phases: Requirements → Design → Coding → Testing → Deployment → Maintenance

# Good for: small projects where the requirements are clear and fixed.
# Advantages: easy to understand, and every phase has clear documentation.
# Disadvantages: changes are hard to make later, and the customer sees the product only at the end.






# 2. Spiral Model

# This model repeats the same steps in loops, and each loop adds more to the product. 
# Its special feature is risk analysis in every loop.

# Each loop has 4 steps: Planning → Risk Analysis → Development (building and testing) → Customer Evaluation

# Good for: big, risky projects.
# Advantages: risks are found early, and changes are easy to handle.
# Disadvantages: it is costly and needs risk experts.






# 3. Incremental Model

# The software is built in small parts called increments. 
# The first increment gives a basic working product, and each next increment adds more features until the full product is ready.

# Good for: projects where the customer wants something working early.
# Advantages: the customer gets a working product early, and it is easy to test and change.
# Disadvantages: it needs good planning and design from the start.






# 4. Scrum

# Scrum is an Agile framework. 
# The team works in short cycles called sprints, which usually last 1 to 4 weeks. At the end of each sprint, a working piece of the product is ready.

# Roles: Product Owner (decides what to build), Scrum Master (helps the team follow Scrum), and the Development Team (builds the product).
# Key parts: Product Backlog (list of all work), Sprint Backlog (work for this sprint), Daily Stand-up (a 15-minute daily meeting), Sprint Review and Retrospective.
# Good for: projects where the requirements keep changing.
# Advantages: it adapts quickly to change, and the customer is always involved.
# Disadvantages: it needs a skilled team, and it is hard to use for large teams.